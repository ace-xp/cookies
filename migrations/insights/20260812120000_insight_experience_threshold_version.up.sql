-- 经验记下它是按哪一版判定阈值判的。
--
-- 「按第 N 版阈值判定」这个印，分析页盖了、复盘的每条发现也盖了，唯独经验没有——
-- 而经验恰恰是这个模块最终交付、也是下一轮唯一会被引用的东西。改完阈值之后回头看
-- 一条老经验，没有这个号码就说不清它当初是按什么标准判的（03 §15 验收 12：任一分析
-- 结论能回溯到判定所依据的东西）。
--
-- NULL 和 0 是两回事，所以这一列可空：
--   NULL = 不知道它按哪一版判的（人自己填的档位、老数据）；
--   0    = 按出厂设定判的。
-- 不可空加个默认 0 的话，全库存量经验会一夜之间都变成「按出厂阈值判定」——
-- 替一条来历不明的结论作保，比什么都不标更糟。

ALTER TABLE insight_experiences
  ADD COLUMN threshold_version BIGINT NULL AFTER confidence;
